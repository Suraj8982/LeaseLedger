CREATE TABLE leases (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id          BIGINT         NOT NULL,
    tenant_id        BIGINT         NOT NULL,
    -- Copied from the property when the lease is created, so "my leases" needs no joins.
    manager_id       BIGINT         NOT NULL,
    start_date       DATE           NOT NULL,
    end_date         DATE           NOT NULL,
    total_rent       NUMERIC(12, 2) NOT NULL,
    installments     INT            NOT NULL,
    security_deposit NUMERIC(12, 2) NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    terminated_on    DATE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_leases_unit FOREIGN KEY (unit_id) REFERENCES units (id),
    CONSTRAINT fk_leases_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_leases_manager FOREIGN KEY (manager_id) REFERENCES users (id),
    CONSTRAINT ck_leases_status CHECK (status IN ('ACTIVE', 'TERMINATED')),
    CONSTRAINT ck_leases_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_leases_rent CHECK (total_rent > 0),
    CONSTRAINT ck_leases_installments CHECK (installments >= 1),
    CONSTRAINT ck_leases_deposit CHECK (security_deposit >= 0)
);

CREATE INDEX ix_leases_manager ON leases (manager_id);
CREATE INDEX ix_leases_tenant ON leases (tenant_id);
CREATE INDEX ix_leases_unit ON leases (unit_id);

CREATE TABLE invoices (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_id          BIGINT         NOT NULL,
    type              VARCHAR(20)    NOT NULL,
    sequence_no       INT            NOT NULL,
    due_date          DATE           NOT NULL,
    amount            NUMERIC(12, 2) NOT NULL,
    status            VARCHAR(20)    NOT NULL,
    paid_at           TIMESTAMP WITH TIME ZONE,
    payment_reference VARCHAR(100),
    -- Optimistic locking: incremented on every update. See Invoice.version.
    version           BIGINT         NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_invoices_lease FOREIGN KEY (lease_id) REFERENCES leases (id),
    -- A lease cannot have two "rent installment 3" invoices. Also serves lookups by lease_id.
    CONSTRAINT uq_invoices_lease_type_seq UNIQUE (lease_id, type, sequence_no),
    CONSTRAINT ck_invoices_type CHECK (type IN ('RENT', 'DEPOSIT')),
    CONSTRAINT ck_invoices_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_invoices_amount CHECK (amount > 0)
);

-- "Overdue" is status = PENDING and due_date < today, so this index serves that query.
CREATE INDEX ix_invoices_status_due ON invoices (status, due_date);
