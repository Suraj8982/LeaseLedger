CREATE TABLE maintenance_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id         BIGINT        NOT NULL,
    tenant_id       BIGINT        NOT NULL,
    manager_id      BIGINT        NOT NULL,
    title           VARCHAR(120)  NOT NULL,
    description     VARCHAR(2000) NOT NULL,
    priority        VARCHAR(20)   NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    resolution_note VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_maintenance_unit FOREIGN KEY (unit_id) REFERENCES units (id),
    CONSTRAINT fk_maintenance_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_maintenance_manager FOREIGN KEY (manager_id) REFERENCES users (id),
    CONSTRAINT ck_maintenance_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_maintenance_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CANCELLED'))
);

-- A manager's work queue is "my requests with status X".
CREATE INDEX ix_maintenance_manager_status ON maintenance_requests (manager_id, status);
CREATE INDEX ix_maintenance_tenant ON maintenance_requests (tenant_id);

-- The database stores where each photo is (its key in the S3 bucket), never the image itself.
CREATE TABLE maintenance_photos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT       NOT NULL,
    object_key   VARCHAR(255) NOT NULL,
    content_type VARCHAR(50)  NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_photos_request FOREIGN KEY (request_id) REFERENCES maintenance_requests (id),
    -- One uploaded file can be attached once.
    CONSTRAINT uq_photos_object_key UNIQUE (object_key)
);

CREATE INDEX ix_photos_request ON maintenance_photos (request_id);
