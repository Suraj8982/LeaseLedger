CREATE TABLE properties (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT       NOT NULL,
    name       VARCHAR(120) NOT NULL,
    address    VARCHAR(255) NOT NULL,
    city       VARCHAR(80)  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_properties_manager FOREIGN KEY (manager_id) REFERENCES users (id)
);

-- Every "my properties" query filters by manager, so that column is indexed.
CREATE INDEX ix_properties_manager ON properties (manager_id);

CREATE TABLE units (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id  BIGINT         NOT NULL,
    unit_number  VARCHAR(20)    NOT NULL,
    bedrooms     INT            NOT NULL,
    -- Money is an exact decimal, never a floating-point number. Amounts are in AED.
    monthly_rent NUMERIC(12, 2) NOT NULL,
    status       VARCHAR(20)    NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_units_property FOREIGN KEY (property_id) REFERENCES properties (id),
    -- "Unit 101" can exist once per building. This index also serves lookups by property_id.
    CONSTRAINT uq_units_property_number UNIQUE (property_id, unit_number),
    CONSTRAINT ck_units_status CHECK (status IN ('VACANT', 'OCCUPIED', 'UNAVAILABLE')),
    CONSTRAINT ck_units_bedrooms CHECK (bedrooms >= 0),
    CONSTRAINT ck_units_rent CHECK (monthly_rent > 0)
);
